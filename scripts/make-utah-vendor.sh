#!/usr/bin/env bash
# Phase 3: vendor/motorola/utah = the firmware images (bootloader, modem, TEE,
# preloader...) that go into the flashable zip, taken from OUR firmware
# (W1WNS36.18-114-3-2-1-1-1), because vendor/motorola/nevada ships the Play's
# older 114-1 set and mixing them is a downgrade. Same file list and sha1 checks as
# nevada's Android.mk. Safe to re-run.
set -euo pipefail
SRC="${SRC:-$HOME/lineage/android}"
FW=$(echo "$HOME"/lineage/firmware/NEVADA*/)
LIST="$SRC/device/motorola/nevada/proprietary-firmware.txt"
OUT="$SRC/vendor/motorola/utah"
rm -rf "$OUT"; mkdir -p "$OUT/radio"
{
  printf '#\n# Generated by scripts/make-utah-vendor.sh from our own firmware. DO NOT EDIT.\n#\n\n'
  printf 'LOCAL_PATH := $(call my-dir)\n\nifeq ($(TARGET_DEVICE),utah)\n\n'
  grep -v '^#' "$LIST" | grep . | while IFS=';' read -r f _; do
    cp "$FW/$f" "$OUT/radio/$f"
    printf '$(call add-radio-file-sha1-checked,radio/%s,%s)\n' "$f" "$(sha1sum "$OUT/radio/$f" | cut -d' ' -f1)"
  done
  printf '\nendif\n'
} > "$OUT/Android.mk"
echo "vendor/motorola/utah: $(ls "$OUT/radio" | wc -l) firmware images"
